#!/usr/bin/env python3
"""Generate swarm's tables (swarm_tables.h).

    python3 engines/swarm/gen_tables.py            write swarm_tables.h
    python3 engines/swarm/gen_tables.py --check    exit 1 if swarm_tables.h is out of date

The knob curves (P1 density, P2 spread, 17 points each, linearly interpolated by the engine), the sixteen saws'
places in the swarm (cluster position, stereo position, inharmonic ratio, swell and drift rates), the particles'
inharmonic ratios and a 256-entry sine for the particles. The inharmonic ratios are the circular membrane's mode
ratios (zeros of the Bessel functions J_m divided by the first, textbook values). Python 3 standard library only.
"""

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "swarm_tables.h")

FS = 44100.0
N = 64
NS = 12
CENT = 65536 / 1200.0                       # Q16 octaves per cent

# circular membrane: j_{m,n} / j_{0,1}, the first sixteen modes in order
MEMBRANE = [1.0, 1.5933, 2.1355, 2.2954, 2.6531, 2.9173, 3.1555, 3.5001, 3.5985, 3.6475, 4.0589, 4.1524,
            4.6010, 4.8314, 4.9037, 5.1336]


def q(x, bits):
    return int(round(x * (1 << bits)))


def oct16(x):
    return int(round(x * 65536))


# ---- P1: density (byte 0 .. 256 in steps of 16) ---------------------------------------------------------------

def p1_curves(b):
    """log2 particles per block, log2 Q of the particle pings, particle and saw layer gains, swell depth."""
    lmu = math.log2(1.5 * N / FS) + 13.0 * b / 192.0          # 1.5 /s at 0, x2 every 14.8 steps
    lmu = min(lmu, 3.0)                                        # at most 8 particles per block (5,500 /s)
    lq = math.log2(250.0) + (math.log2(25.0) - math.log2(250.0)) * min(b, 192) / 192.0
    t = min(max((b - 112) / 112.0, 0.0), 1.0)                  # the crossfade, 112 .. 224
    gp, gs = math.cos(math.pi / 2 * t), math.sin(math.pi / 2 * t)
    depth = 0.85 - 0.5 * min(max((b - 112) / 143.0, 0.0), 1.0)
    return lmu, lq, gp, gs, depth


# ---- P2: spread (byte 0 .. 256 in steps of 16) ----------------------------------------------------------------

def p2_curves(b):
    """cluster half-width (cents), inharmonic share 0..1, stereo width 0..1."""
    b = min(b, 255)
    if b <= 128:
        s = 50.0 * (b / 128.0) ** 2
        i = 0.0
    elif b <= 192:
        s = 50.0 + 150.0 * (b - 128) / 64.0
        i = 0.0
    else:
        x = (b - 192) / 63.0
        s = 200.0 - 170.0 * x
        i = x * x * (3 - 2 * x)
    w = 0.6 + 0.4 * min(1.0, b / 32.0)
    return s, i, w


# ---- the sixteen saws -----------------------------------------------------------------------------------------

def saws():
    """cluster position -1..1, pan -1..1, log2 inharmonic ratio, swell rate (Hz), drift rate (Hz), per saw.
    Saw 0 is the centre (it enters first and anchors the note); then pairs, one flat and one sharp, the flat one
    alternating between the sides; the last saw is a lone sharp one."""
    pos, pan, ratio = [0.0], [0.0], [0.0]
    pans = [0.85, 0.45, 1.0, 0.3, 0.7]
    order = [1, 3, 5, 7, 9, 2, 4, 6, 8, 10, 11]                   # membrane modes, interleaved low and high
    for j in range(5):
        c = ((j + 1) / 5.5) ** 1.2 * (1 + 0.04 * math.sin(3.1 * j + 0.7))
        side = 1 if j % 2 == 0 else -1
        pos += [-c, c]
        pan += [-side * pans[j], side * pans[j]]
    pos.append(1.0)
    pan.append(0.15)
    for k in range(1, NS):
        ratio.append(math.log2(MEMBRANE[order[k - 1]]))
    swell = [0.13 + 0.5 * ((k * 0.618034) % 1.0) for k in range(NS)]
    drift = [0.05 + 0.25 * ((k * 0.381966 + 0.3) % 1.0) for k in range(NS)]
    return pos, pan, ratio, swell, drift


def per_block(hz):
    """A frequency as a phase increment per 64-sample block, Q32."""
    return int(round(hz * N / FS * 2 ** 32))


def generate():
    L = []
    L.append("/* swarm_tables.h - generated by gen_tables.py, do not edit. */")
    L.append("#ifndef SWARM_TABLES_H")
    L.append("#define SWARM_TABLES_H")
    L.append("")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("#define SWARM_SAWS %d" % NS)
    L.append("")
    rows = [p1_curves(16 * i) for i in range(17)]
    L.append("/* P1 (density) at bytes 0, 16 .. 256: log2 particles per block (Q16), log2 Q of the pings (Q16),")
    L.append(" * particle layer gain, saw layer gain, swell depth (Q15). */")
    L.append("static const int32_t k_p1_lmu[17] = { %s };" % ", ".join(str(oct16(r[0])) for r in rows))
    L.append("static const int32_t k_p1_lq[17] = { %s };" % ", ".join(str(oct16(r[1])) for r in rows))
    L.append("static const int16_t k_p1_gp[17] = { %s };" % ", ".join(str(min(32767, q(r[2], 15))) for r in rows))
    L.append("static const int16_t k_p1_gs[17] = { %s };" % ", ".join(str(min(32767, q(r[3], 15))) for r in rows))
    L.append("static const int16_t k_p1_depth[17] = { %s };" % ", ".join(str(q(r[4], 15)) for r in rows))
    rows = [p2_curves(16 * i) for i in range(17)]
    L.append("")
    L.append("/* P2 (spread) at bytes 0, 16 .. 256: cluster half-width (Q16 octaves), inharmonic share and stereo")
    L.append(" * width (Q15). */")
    L.append("static const int32_t k_p2_spread[17] = { %s };" % ", ".join(str(int(round(r[0] * CENT))) for r in rows))
    L.append("static const int16_t k_p2_inh[17] = { %s };" % ", ".join(str(min(32767, q(r[1], 15))) for r in rows))
    L.append("static const int16_t k_p2_width[17] = { %s };" % ", ".join(str(min(32767, q(r[2], 15))) for r in rows))
    pos, pan, ratio, swell, drift = saws()
    L.append("")
    L.append("/* The saws: cluster position and pan (Q15, -1..1), log2 of the inharmonic ratio (Q16), swell and drift")
    L.append(" * rates (phase per block, Q32); the tilt 1 - 1 / sqrt(ratio) (Q15) the inharmonic weights move by. */")
    L.append("static const int16_t k_saw_pos[SWARM_SAWS] = { %s };" % ", ".join(str(max(-32767, min(32767, q(x, 15))))
                                                                      for x in pos))
    L.append("static const int16_t k_saw_pan[SWARM_SAWS] = { %s };" % ", ".join(str(max(-32767, min(32767, q(x, 15))))
                                                                      for x in pan))
    L.append("static const int32_t k_saw_l2r[SWARM_SAWS] = { %s };" % ", ".join(str(oct16(x)) for x in ratio))
    L.append("static const int16_t k_saw_tilt[SWARM_SAWS] = { %s };"
             % ", ".join(str(q(1 - 2 ** (-x / 2), 15)) for x in ratio))
    L.append("static const uint32_t k_saw_swell[SWARM_SAWS] = { %s };" % ", ".join("%du" % per_block(x) for x in swell))
    L.append("static const uint32_t k_saw_drift[SWARM_SAWS] = { %s };" % ", ".join("%du" % per_block(x) for x in drift))
    part = [0.0, 0.0, 0.0] + [math.log2(MEMBRANE[i]) for i in range(1, 6)]
    L.append("")
    L.append("/* The particles' inharmonic ratios (log2, Q16): the note three times out of eight, then five membrane modes. */")
    L.append("static const int32_t k_part_l2r[8] = { %s };" % ", ".join(str(oct16(x)) for x in part))
    L.append("")
    L.append("/* A sine of 256 steps for linear interpolation, one load per sample (engines/modal's layout): the low half")
    L.append(" * is the step d from sin(2 pi i / 256) to sin(2 pi (i + 1) / 256) (Q15, signed), the high half the value the")
    L.append(" * step is taken from. The fraction is the signed low half of phase >> 9, whose top bit is the index's lowest")
    L.append(" * bit: even entries see 0 .. 1 and hold sin(i), odd entries see -1 .. 0 and hold sin(i + 1). */")
    a = [int(round(32767 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
    words = []
    for i in range(256):
        d = a[(i + 1) % 256] - a[i]
        base = a[i] if i % 2 == 0 else a[(i + 1) % 256]
        words.append("0x%08x" % (((base & 0xffff) << 16) | (d & 0xffff)))
    L.append("static const int32_t k_sin[256] = {")
    for i in range(0, 256, 8):
        L.append("    (int32_t)" + ", (int32_t)".join(words[i:i + 8]) + ",")
    L.append("};")
    L.append("")
    L.append("#endif")
    return "\n".join(L) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        with open(OUT) as f:
            if f.read() != text:
                print("swarm_tables.h is out of date: run python3 engines/swarm/gen_tables.py")
                return 1
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
