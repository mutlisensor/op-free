/*
 * fm2 — two-operator FM voice: one sine modulator with feedback into one sine carrier.
 *
 *   P1        ratio       modulator : carrier frequency, 16 steps of 16 values (P1 / 16 picks the step):
 *                         0.5 1 1.5 2 3 4 5 6 7 9 11 14, then 2 drifting (+0.7 Hz), 1.41 (sqrt 2), 3.5, 3.14 (pi)
 *   P2        index       modulation depth: 0 .. 191 index 0 -> 4 rad (quadratic, so the low end is fine-grained);
 *                         192 .. 255 index 4 -> 6.28 rad and modulator feedback 0 -> 2 rad (gritty at the top)
 *   envelope              the index follows the host envelope's level (attack swells, decay/sustain mellow,
 *                         release darkens), so the OP-Z's attack .. release shape the brightness as well as the level
 *   velocity              level, base index (50 % at velocity 0 .. 100 % at 127) and a "strike": up to +100 % index
 *                         at note-on that dies away with a time constant of 150 ms at C4 (halving every two octaves
 *                         up, 40 .. 400 ms)
 *   anti-aliasing         index limited so the highest strong sideband, f_c + (index + 1) f_m, stays below 16 kHz;
 *                         feedback fades out as that room drops from 20 to 4 sidebands (ratio 1: above ~740 Hz)
 *
 * The filter and resonance knobs are the OS's own track filter, which runs after the engine; fm2 never reads them.
 *
 * Inspired by the OP-1's FM engine and classic two-operator FM chips (Chowning's ratios, the DX family's averaged
 * operator feedback); written from scratch. MIT licence, see CONTRIBUTING.md.
 */
#include "opz_adsr.h"
#include "opz_dsp.h"
#include "opz_engine.h"
#include "opz_mix.h"

typedef struct State {
    uint32_t pc, pm;         /* carrier and modulator phase, Q32 turns */
    int32_t m0, m1;          /* last two modulator outputs, Q15 (feedback averages them) */
    int32_t d;               /* index after the envelope at the end of the last block, Q16 of index units */
    int32_t fb;              /* feedback at the end of the last block, Q16 of index units */
    fract32 strike;          /* velocity strike, 1 at note-on, decays once per block (Q31) */
    fract32 strike_k;        /* its per-block multiplier (Q31) */
    int32_t vel15;           /* velocity, Q15 */
    int32_t amp15;           /* velocity x OPZ_VOICE_PEAK, Q15 (a gain needs no more than 16 bits) */
    int32_t fresh;           /* first block after note-on: start at the target feedback, no ramp */
    OpzMix mix;              /* the track's level and pan (opz_mix.h) */
    int16_t buf[OPZ_BLOCK_FRAMES];  /* render's scratch: modulator, then carrier, Q15 */
} State;

_Static_assert(sizeof(State) <= OPZ_VOICE_STATE_BYTES, "voice state must fit in 280 bytes");

