#!/usr/bin/env python3
"""Generate engines/vowel/vowel_tables.h: the vowel formant table.

    python3 engines/vowel/gen_tables.py > engines/vowel/vowel_tables.h

Four formants per vowel: centre frequency, bandwidth and peak level, for an adult male (tenor / baritone) voice,
the size P2 64 plays. Our own table, rounded from published phonetic averages: Peterson & Barney (1952) for the
spoken vowels' F1-F3, Fant (1960) and Sundberg (The Science of the Singing Voice, 1987) for bandwidths, the
singer's F3/F4 cluster and the levels of sung vowels. Values were then nudged so that neighbours on the P1 path
morph through plausible vowels and every vowel has about the same loudness (see vowel.c).

Stored as int16 log2 values in Q11 (1/2048 octave): log2(Hz) for frequencies and bandwidths, log2(amplitude) for
the levels (dB / 6.0206). Python 3 standard library only.
"""

import math

# name, IPA, (F1..F4 Hz), (B1..B4 Hz), (L1..L4 dB, F1 = 0)
VOWELS = [
    ("hum", "m", (250, 1100, 2350, 3200), (70, 200, 250, 300), (0, -24, -30, -36)),
    ("oo", "u", (310, 780, 2350, 3250), (50, 70, 110, 140), (0, -14, -28, -34)),
    ("oh", "o", (420, 820, 2500, 3250), (55, 80, 110, 140), (0, -8, -22, -30)),
    ("ah", "a", (720, 1120, 2550, 3350), (80, 90, 120, 140), (0, -4, -14, -22)),
    ("eh", "e", (480, 1800, 2550, 3400), (60, 90, 110, 130), (0, -12, -14, -22)),
    ("ee", "i", (280, 2250, 3000, 3550), (50, 100, 120, 140), (0, -16, -14, -22)),
    ("ue", "y", (280, 1700, 2200, 3300), (50, 90, 110, 140), (0, -14, -14, -24)),
    ("er", "r", (480, 1330, 1700, 3300), (60, 80, 90, 140), (0, -8, -8, -24)),
]


def q11(x):
    return int(round(x * 2048))


def main():
    print("/* Generated by gen_tables.py; do not edit. MIT licence, see CONTRIBUTING.md. */")
    print("#ifndef VOWEL_TABLES_H")
    print("#define VOWEL_TABLES_H")
    print()
    print("#define VOWELS %d" % len(VOWELS))
    print()
    print("/* Per vowel (P1 order) and formant: log2(F / Hz), log2(B / Hz), log2(level), all Q11. Male voice. */")
    print("static const int16_t k_vowel[VOWELS][4][3] = {")
    for name, ipa, f, b, l in VOWELS:
        rows = ", ".join("{ %d, %d, %d }" % (q11(math.log2(f[k])), q11(math.log2(b[k])), q11(l[k] / 6.0206))
                         for k in range(4))
        print("    { %s },   /* %s [%s] */" % (rows, name, ipa))
    print("};")
    print()
    print("/* Gain of the velocity tone (an analog one-pole low-pass) at d octaves above its corner, as a cut in octaves:")
    print(" * log2(1 + 4^d) / 2, d = -4 .. 4 in quarter octaves, Q16. */")
    vals = [int(round(math.log2(1 + 4 ** (i / 4 - 4)) / 2 * 65536)) for i in range(33)]
    print("static const int32_t k_tone[33] = {")
    for i in range(0, 33, 11):
        print("    " + ", ".join(str(v) for v in vals[i:i + 11]) + ",")
    print("};")
    print()
    print("#endif")


if __name__ == "__main__":
    main()
