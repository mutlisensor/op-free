#!/usr/bin/env python3
"""Generate engines/super/super_tables.h: the detune curve and the normalised mix gains.

    python3 engines/super/gen_tables.py > engines/super/super_tables.h

The detune curve and the centre/side mix curves are the polynomial fits Adam Szabo published for the Roland
JP-8000's supersaw ("How to Emulate the Super Saw", 2010); the per-saw offsets are the ones measured there. The
gains are normalised here so the level per channel stays the same over the whole P2 range. Python 3 standard
library only.
"""

import math

# Szabo's 11th-order fit of the detune knob (x 0..1) to the detune amount (0..1).
DETUNE_POLY = [10028.7312891634, -50818.8652045924, 111363.4808729368, -138150.6761080548, 106649.6679158292,
               -53046.9642751875, 17019.9518580080, -3425.0836591318, 404.2703938388, -24.1878824391,
               0.6717417634, 0.0030115596]

# Pan of the three side-saw pairs (super.c): outer 0.75, middle 1.0, inner 0.5. Power of one channel, L = M + S,
# relative to one saw: centre^2 + side^2 * sum over the six side saws of (1 + p)^2.
PANS = (0.75, 1.0, 0.5)
SIDE_POWER = sum((1 + p) ** 2 + (1 - p) ** 2 for p in PANS)       # 9.625

T = 0.15            # internal RMS per channel (Q31 full scale = 1); peaks stay below ~0.6
SUB_MAX = 1.0       # triangle sub amplitude at P2 255, relative to one saw
DETUNE_POINTS = 65  # P1 0..1 in 64 steps
MIX_POINTS = 33     # P2 0..1 in 32 steps; mix to 24/32, sub above


def detune(x):
    r = 0.0
    for c in DETUNE_POLY:
        r = r * x + c
    return min(max(r, 0.0), 1.0)


def mix(p2):
    x = min(p2 / 0.75, 1.0)
    sub = max(0.0, (p2 - 0.75) / 0.25) * SUB_MAX
    centre = -0.55366 * x + 0.99785
    side = -0.73764 * x * x + 1.2841 * x + 0.044372
    norm = T * math.sqrt(3.0) / math.sqrt(centre ** 2 + SIDE_POWER * side ** 2 + sub ** 2)
    return norm * centre, norm * side, norm * sub


def q31(v):
    return max(-0x80000000, min(0x7fffffff, int(round(v * 2 ** 31))))


def rows(values, per_line=6):
    out = []
    for i in range(0, len(values), per_line):
        out.append("    " + " ".join("%d," % v for v in values[i:i + per_line]))
    return "\n".join(out)


def main():
    d = [q31(detune(i / (DETUNE_POINTS - 1))) for i in range(DETUNE_POINTS)]
    m = [mix(i / (MIX_POINTS - 1)) for i in range(MIX_POINTS)]
    print("/* Generated by gen_tables.py; do not edit. MIT licence, see CONTRIBUTING.md. */")
    print("#ifndef SUPER_TABLES_H\n#define SUPER_TABLES_H\n")
    print("/* Detune amount 0..1 (Q31) for P1 = i / %d. */" % (DETUNE_POINTS - 1))
    print("static const int32_t k_detune[%d] = {\n%s\n};\n" % (DETUNE_POINTS, rows(d)))
    print("/* Centre-saw, side-saw and sub gains (Q31) for P2 = i / %d, normalised to RMS %.2f per channel. */"
          % (MIX_POINTS - 1, T))
    for name, k in (("k_centre", 0), ("k_side", 1), ("k_sub", 2)):
        print("static const int32_t %s[%d] = {\n%s\n};\n" % (name, MIX_POINTS, rows([q31(r[k]) for r in m])))
    print("#endif")


if __name__ == "__main__":
    main()
