#!/usr/bin/env python3
"""Generate mallet's tables (mallet_tables.h).

    python3 engines/mallet/gen_tables.py            write mallet_tables.h
    python3 engines/mallet/gen_tables.py --check    exit 1 if mallet_tables.h is out of date

The nine materials P1 morphs between, mode by mode: frequency ratios (log2-interpolated by the engine), strike
weights and relative decay times, and per material its natural ring (the fundamental's T60 at P2 128 on a low note),
its high-frequency damping, its mallet's hardness and the strike click. Then a 256-entry sine table with its deltas
for linear interpolation, the 2^-x table of the decays and the phase increments of the top octave of MIDI notes.

The free-bar ratios are the textbook values of an ideal free-free (Euler-Bernoulli) bar; the marimba (1 : 3.99 :
9.95), xylophone (1 : 3 : 6), vibraphone (1 : 4 : 10), steel pan (harmonic fundamental, octave and twelfth), church
bell (hum, prime, minor tierce, quint, nominal) and wine glass ratios are our approximations of published
measurements (Fletcher and Rossing, The Physics of Musical Instruments); the wood block and the gong are our own
dense, inharmonic sets. Python 3 standard library only. MIT licence, see CONTRIBUTING.md.
"""

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "mallet_tables.h")

NMODES = 10

# name, ratios, strike weights (relative amplitude), relative T60,
# natural T60 of the fundamental in seconds (P2 128, a low note: the damping below shortens high notes),
# high-frequency damping h (the T60 of a partial at f kHz is divided by 1 + h f at P2 128),
# mallet hardness in octaves (moves the strike's low-pass corner), click amount (mallet noise, 0..1),
# level trim in dB (evens out the materials' peaks at full velocity, P2 128)
