def q(x, bits):
    return int(round(x * (1 << bits)))


def note_inc(n):
    return int(round(440.0 * 2.0 ** ((n - 69) / 12.0) / 44100.0 * 2 ** 32))


def generate():
    for name, r, w, d, t, h, m, c, lv in MATERIALS:
        assert len(r) == len(w) == len(d) == NMODES, name
        assert r[0] == 1 and w[0] == 1.0, name           # mode 0 is the note itself
        assert max(r) < 64 and min(r) >= 0.25, name      # Q16 fits, and the engine's band checks hold
        assert 0 < t <= 16 and h > 0 and 0 <= c <= 1 and -6 <= lv <= 3.5, name   # trim <= x1.5: headroom
    L = []
    L.append("/* mallet_tables.h — generated by gen_tables.py; do not edit. MIT licence, see CONTRIBUTING.md. */")
    L.append("#ifndef MALLET_TABLES_H")
    L.append("#define MALLET_TABLES_H")
    L.append("")
    L.append("#define MALLET_NMODES %d" % NMODES)
    L.append("#define MALLET_MATERIALS %d" % len(MATERIALS))
    L.append("")
    L.append("/* Materials, P1 0 -> 255 in %d equal zones: %s */" % (len(MATERIALS) - 1,
                                                                  ", ".join(a[0] for a in MATERIALS)))
    L.append("/* frequency ratio of each mode in each material, Q16 (exact at the anchors) */")
    L.append("static const uint32_t k_ratio[MALLET_MATERIALS][MALLET_NMODES] = {")
    for a in MATERIALS:
        L.append("    { %s },   /* %s */" % (", ".join(str(q(x, 16)) for x in a[1]), a[0]))
    L.append("};")
    L.append("/* log2 of the ratio step to the next material, Q16 (the engine interpolates ratios in log2) */")
    L.append("static const int32_t k_dlog[MALLET_MATERIALS - 1][MALLET_NMODES] = {")
    for a, b in zip(MATERIALS, MATERIALS[1:]):
        L.append("    { %s },   /* %s -> %s */" % (", ".join(str(q(math.log2(y / x), 16))
                                                            for x, y in zip(a[1], b[1])), a[0], b[0]))
    L.append("};")
    L.append("/* strike weight, Q15 */")
    L.append("static const int16_t k_weight[MALLET_MATERIALS][MALLET_NMODES] = {")
    for a in MATERIALS:
        L.append("    { %s },   /* %s */" % (", ".join(str(min(32767, q(x, 15))) for x in a[2]), a[0]))
    L.append("};")
    L.append("/* log2 of the mode's T60 relative to the fundamental's, Q12 */")
    L.append("static const int16_t k_ldecay[MALLET_MATERIALS][MALLET_NMODES] = {")
    for a in MATERIALS:
        L.append("    { %s },   /* %s */" % (", ".join(str(q(math.log2(x), 12)) for x in a[3]), a[0]))
    L.append("};")
    L.append("/* per material: log2 of the natural T60 (s), log2 of the damping h (per kHz), mallet hardness (octaves),")
    L.append(" * all Q12; click amount, Q15; level trim, Q14 (16384 = 0 dB) */")
    L.append("typedef struct Material { int16_t lgt, lgh, hard, click, trim; } Material;")
    L.append("static const Material k_mat[MALLET_MATERIALS] = {")
    for a in MATERIALS:
        L.append("    { %d, %d, %d, %d, %d },   /* %s */" % (q(math.log2(a[4]), 12), q(math.log2(a[5]), 12),
                                                             q(a[6], 12), min(32767, q(a[7], 15)),
                                                             q(10 ** (a[8] / 20), 14), a[0]))
    L.append("};")
    L.append("")
    L.append("/* A sine of 256 steps for linear interpolation, one load per sample: the low half is the step d from")
    L.append(" * sin(2 pi i / 256) to sin(2 pi (i + 1) / 256) (Q15, signed), the high half the value the step is taken from.")
    L.append(" * The engine reads the fraction as the signed low half of phase >> 9, whose top bit is the index's lowest")
    L.append(" * bit: even entries see 0 .. 1 and hold sin(i), odd entries see -1 .. 0 and hold sin(i + 1), which saves")
    L.append(" * masking it. Peak error (interpolation and rounding) 3.3 LSB, -80 dBFS. (As engines/modal.) */")
    s = [int(round(32767 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
    words = []
    for i in range(256):
        d = s[(i + 1) % 256] - s[i]
        base = s[i] if i % 2 == 0 else s[(i + 1) % 256]
        words.append("0x%08x" % (((base & 0xffff) << 16) | (d & 0xffff)))
    L.append("static const int32_t k_sin[256] = {")
    for i in range(0, 256, 8):
        L.append("    (int32_t)" + ", (int32_t)".join(words[i:i + 8]) + ",")
    L.append("};")
    L.append("")
    L.append("/* 2^(-j / 64) in Q31, j = 0 .. 64: the decays' 2^-x per block takes the top 6 bits of x's fraction here */")
    e = [min(0x7fffffff, int(round(2 ** (-j / 64) * 2 ** 31))) for j in range(65)]
    L.append("static const int32_t k_exp2n[65] = {")
    for i in range(0, 65, 8):
        L.append("    " + ", ".join(str(x) for x in e[i:i + 8]) + ",")
    L.append("};")
    L.append("")
    L.append("/* phase increments (Q32 turns per sample at 44.1 kHz, A4 = 69 = 440 Hz) of MIDI notes 120 .. 131: note n is")
    L.append(" * k_note_inc[n % 12] >> (10 - n / 12) */")
    L.append("static const uint32_t k_note_inc[12] = { %s };" % ", ".join("%du" % note_inc(n) for n in range(120, 132)))
    L.append("")
    L.append("#endif")
    return "\n".join(L) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT) as f:
                same = f.read() == text
        except OSError:
            same = False
        if not same:
            print("mallet_tables.h is out of date: run python3 engines/mallet/gen_tables.py")
            return 1
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
